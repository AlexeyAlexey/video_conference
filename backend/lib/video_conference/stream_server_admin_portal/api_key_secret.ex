defmodule VideoConference.StreamServerAdminPortal.ApiKeySecret do
  @moduledoc """
  Shared API key secret generation and hashing for the stream server
  admin portal.

  Both application API keys (`Applications.create_api_key/1`) and stream
  server API keys (`StreamServers.create_stream_server_api_key/1`) use
  this module so both scopes generate and hash secrets the same way.
  """

  @doc """
  Generates a random API key secret in the form
  `env_prefix <> "_" <> prefix_id <> "_" <> <random>` so leaked keys are
  recognizable in logs and config scans and keys can be found by their
  `env_prefix <> "_" <> prefix_id` prefix. Stream server API keys pass
  `"ssak"` ("stream server api key"), application API keys pass `"aak"`
  ("application api key"), each with an independently generated id as
  `prefix_id`.
  """
  def generate(env_prefix, prefix_id)
      when is_binary(env_prefix) and is_binary(prefix_id) do
    prefix(env_prefix, prefix_id) <>
      "_" <> Base.url_encode64(:crypto.strong_rand_bytes(32), padding: false)
  end

  @doc """
  Returns the `env_prefix <> "_" <> prefix_id` lookup prefix embedded at
  the start of a secret generated by `generate/2`.
  """
  def prefix(env_prefix, prefix_id)
      when is_binary(env_prefix) and is_binary(prefix_id) do
    env_prefix <> "_" <> prefix_id
  end

  @doc """
  Hashes an API key secret with bcrypt for storage.
  """
  def hash(secret) when is_binary(secret) do
    Bcrypt.hash_pwd_salt(secret)
  end

  @doc """
  Verifies a plaintext API key secret against a stored bcrypt hash.
  """
  def verify(secret, hashed_secret)
      when is_binary(secret) and is_binary(hashed_secret) do
    Bcrypt.verify_pass(secret, hashed_secret)
  end
end
